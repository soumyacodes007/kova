#!/usr/bin/env python
"""OpenAPI -> TypeScript types without node (owner: agent C). The fallback for `export-openapi.py`.

    python scripts/gen-ts-types.py [docs/api/openapi.json] [-o apps/web/lib/api-types.ts]

Emits the same top-level shape as `openapi-typescript` (`paths`, `components["schemas"]`, `operations`), so
frontend code imports the same names whichever generator produced the file:

    import type { components } from "@/lib/api-types";
    type Leaderboard = components["schemas"]["Leaderboard"];
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
HEADER = """/**
 * This file was auto-generated by scripts/gen-ts-types.py from docs/api/openapi.json.
 * Do not make direct changes to the file; run `python scripts/export-openapi.py` instead.
 */
"""


def _key(name: str) -> str:
    return name if IDENT.match(name) else json.dumps(name)


def _doc(text: str | None, indent: str) -> str:
    if not text:
        return ""
    lines = [ln.rstrip() for ln in text.strip().splitlines()]
    if len(lines) == 1:
        return f"{indent}/** {lines[0]} */\n"
    return f"{indent}/**\n" + "".join(f"{indent} * {ln}\n" if ln else f"{indent} *\n" for ln in lines) + f"{indent} */\n"


def ts_type(s: dict, indent: str = "") -> str:
    """One JSON-schema node as a TypeScript type expression."""
    if "$ref" in s:
        return f'components["schemas"]["{s["$ref"].rsplit("/", 1)[-1]}"]'
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    for combo in ("anyOf", "oneOf"):
        if combo in s:
            parts = []
            for p in s[combo]:
                t = ts_type(p, indent)
                if t not in parts:
                    parts.append(t)
            return " | ".join(parts)
    if "allOf" in s:
        return " & ".join(ts_type(p, indent) for p in s["allOf"])
    t = s.get("type")
    if isinstance(t, list):
        return " | ".join(ts_type({**s, "type": x}, indent) for x in t)
    if t in ("integer", "number"):
        return "number"
    if t == "string":
        return "string"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        if "prefixItems" in s:
            return "[" + ", ".join(ts_type(p, indent) for p in s["prefixItems"]) + "]"
        inner = ts_type(s.get("items", {}), indent)
        return f"({inner})[]" if "|" in inner or "&" in inner else f"{inner}[]"
    if t == "object" or "properties" in s or "additionalProperties" in s:
        return _object(s, indent)
    return "unknown"


def _object(s: dict, indent: str) -> str:
    props = s.get("properties", {})
    required = set(s.get("required", []))
    extra = s.get("additionalProperties")
    if not props:
        if isinstance(extra, dict) and extra:
            return f"{{\n{indent}    [key: string]: {ts_type(extra, indent + '    ')};\n{indent}}}"
        return "Record<string, unknown>" if extra in (True, {}, None) else "Record<string, never>"
    inner = indent + "    "
    out = ["{\n"]
    for name, p in props.items():
        out.append(_doc(p.get("description"), inner))
        out.append(f"{inner}{_key(name)}{'' if name in required else '?'}: {ts_type(p, inner)};\n")
    if isinstance(extra, dict) and extra:
        out.append(f"{inner}[key: string]: {ts_type(extra, inner)};\n")
    out.append(f"{indent}}}")
    return "".join(out)


def _params(op: dict, where: str) -> dict:
    return {p["name"]: p for p in op.get("parameters", []) if p.get("in") == where}


def _param_block(params: dict, indent: str) -> str:
    out = ["{\n"]
    for name, p in params.items():
        out.append(_doc(p.get("description") or p.get("schema", {}).get("description"), indent + "    "))
        opt = "" if p.get("required") else "?"
        out.append(f"{indent}    {_key(name)}{opt}: {ts_type(p.get('schema', {}), indent + '    ')};\n")
    out.append(f"{indent}}}")
    return "".join(out)


def _response(op: dict, indent: str) -> str:
    out = ["{\n"]
    for code, resp in op.get("responses", {}).items():
        out.append(f"{indent}    {_key(str(code))}: {{\n{indent}        content: {{\n")
        for media, body in (resp.get("content") or {}).items():
            schema = body.get("schema")
            out.append(f"{indent}            {_key(media)}: "
                       f"{ts_type(schema, indent + '            ') if schema else 'unknown'};\n")
        out.append(f"{indent}        }};\n{indent}    }};\n")
    out.append(f"{indent}}}")
    return "".join(out)


def _operation(op: dict) -> str:
    out = ["{\n        parameters: {\n"]
    for label in ("query", "header", "path", "cookie"):
        group = _params(op, label)
        body = _param_block(group, "            ") if group else "never"
        opt = "" if label == "path" and group else "?"
        out.append(f"            {label}{opt}: {body};\n")
    out.append("        };\n        requestBody?: never;\n")
    out.append(f"        responses: {_response(op, '        ')};\n    }}")
    return "".join(out)


METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")


def generate(spec: dict) -> str:
    out = [HEADER, "export interface paths {\n"]
    ops: dict[str, dict] = {}
    for path, item in spec.get("paths", {}).items():
        out.append(f"    {json.dumps(path)}: {{\n        parameters: {{\n            query?: never;\n"
                   "            header?: never;\n            path?: never;\n            cookie?: never;\n        };\n")
        for method in METHODS:
            op = item.get(method)
            if op is None:
                out.append(f"        {method}?: never;\n")
                continue
            out.append(_doc(op.get("summary") or op.get("description"), "        "))
            out.append(f'        {method}: operations["{op["operationId"]}"];\n')
            ops[op["operationId"]] = op
        out.append("    };\n")
    out.append("}\nexport type webhooks = Record<string, never>;\n")
    out.append("export interface components {\n    schemas: {\n")
    for name, s in spec.get("components", {}).get("schemas", {}).items():
        out.append(_doc(s.get("description"), "        "))
        out.append(f"        {_key(name)}: {ts_type(s, '        ')};\n")
    out.append("    };\n    responses: never;\n    parameters: never;\n    requestBodies: never;\n"
               "    headers: never;\n    pathItems: never;\n}\nexport type $defs = Record<string, never>;\n")
    out.append("export interface operations {\n")
    for op_id, op in ops.items():
        out.append(f"    {_key(op_id)}: {_operation(op)};\n")
    out.append("}\n")
    return "".join(out)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("spec", nargs="?", default=str(REPO / "docs/api/openapi.json"))
    p.add_argument("-o", "--out", default=str(REPO / "apps/web/lib/api-types.ts"))
    a = p.parse_args(argv)
    spec = json.loads(Path(a.spec).read_text(encoding="utf-8"))
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(generate(spec), encoding="utf-8", newline="\n")
    print(f"wrote {out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
